// 获取交易所图标的函数
export const getExchangeIcon = (
  exchangeType: string,
  props: IconProps = {}
) => {
  // 支持完整ID或类型名
  const type = exchangeType.toLowerCase().includes('binance')
    ? 'binance'
    : exchangeType.toLowerCase().includes('hyperliquid')
      ? 'hyperliquid'
      : exchangeType.toLowerCase().includes('aster')
        ? 'aster'
        : exchangeType.toLowerCase()
          ? 'apex'
          : exchangeType.toLowerCase()

  const iconProps = {
    width: props.width || 24,
    height: props.height || 24,
    className: props.className,
  }

  switch (type) {
    case 'binance':
    case 'cex':
      return <BinanceIcon {...iconProps} />
    case 'hyperliquid':
    case 'dex':
      return <HyperliquidIcon {...iconProps} />
    case 'aster':
      return <AsterIcon {...iconProps} />
      case 'apex':
        return <ApexIcon {...iconProps} />
    default:
      return (
        <div
          className={props.className}
          style={{
            width: props.width || 24,
            height: props.height || 24,
            borderRadius: '50%',
            background: '#2B3139',
            display: 'flex',
            alignItems: 'center',
            justifyContent: 'center',
            fontSize: '12px',
            fontWeight: 'bold',
            color: '#EAECEF',
          }}
        >
          {type[0]?.toUpperCase() || '?'}
        </div>
      )
  }
}
